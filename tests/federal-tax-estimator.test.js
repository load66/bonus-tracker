'use strict';
const assert=require('node:assert/strict');
require('../federal-tax-estimator.js');
const calc=globalThis.BTFederalTax;
assert(calc,'Estimator available');
const estimate=x=>calc.estimate({year:2026,filingStatus:'single',otherIncome:'80000',bonusAmount:325,...x});
const dollars=n=>Math.round(n*100)/100;
const base=estimate({});
assert(base.ok);
assert.equal(base.deduction,16100);
assert.equal(base.baselineTax,8770);
assert.equal(base.federalTax,8841.5);
assert.equal(base.bonusTax,71.5,'2026 marginal 22% for $80k salary and $325 bonus');
assert.equal(base.balance,null,'Never claim an IRS balance without withholding');
assert.equal(base.marginalRate,.22);
const withheld=estimate({withholding:'9000'});
assert.equal(withheld.balance,-158.5,'Projected withholding yields potential refund, not automatically bill');
assert.equal(estimate({withholding:'8000',payments:'100'}).balance,741.5,'Estimated payments reduce outstanding projected income tax');
// Qualified overtime is explicitly entered FLSA premium, not automatically
// assumed from an overtime paycheck. 2026 W-2 box 12 code TT is authoritative.
const withOT=estimate({qualifiedOvertime:2000,withholding:9000});
assert.equal(withOT.qualifiedOvertime,2000);
assert.equal(withOT.overtimeDeduction,2000);
assert.equal(withOT.federalTax,8401.50);
assert.equal(withOT.bonusTax,71.50,'OT deduction applies both with and without existing bank bonuses');
assert.equal(withOT.balance,-598.50,'OT deduction reduces the estimated balance due');
assert.equal(estimate({qualifiedOvertime:20000}).overtimeDeduction,12500,'Single cap is $12,500');
assert.equal(estimate({filingStatus:'mfj',qualifiedOvertime:26000}).overtimeDeduction,25000,'Joint cap is $25,000');
assert.equal(estimate({filingStatus:'mfs',qualifiedOvertime:100}).reason,'overtime-filing-status','MFS cannot claim the deduction');
assert.equal(estimate({qualifiedOvertime:-1}).reason,'qualified-overtime');
assert.equal(estimate({qualifiedOvertime:'1000.123'}).reason,'qualified-overtime');
assert.equal(estimate({qualifiedOvertime:''}).overtimeDeduction,0);
const phaseout=estimate({otherIncome:151200,bonusAmount:0,qualifiedOvertime:2000});
assert.equal(phaseout.overtimeDeduction,1900,'IRS schedule phases out $100 per completed $1k over MAGI threshold');
assert(phaseout.overtimePhaseoutEstimated,'Estimated MAGI must be labeled as a proxy');
assert.equal(estimate({otherIncome:150999,bonusAmount:0,qualifiedOvertime:2000}).overtimeDeduction,2000,'Partial $1000 above threshold does not phase out');
const phaseoutBonus=estimate({otherIncome:151500,bonusAmount:700,qualifiedOvertime:2000});
assert.equal(phaseoutBonus.overtimeDeductionBefore,1900);
assert.equal(phaseoutBonus.overtimeDeduction,1800);
assert.equal(phaseoutBonus.bonusTax,192,'Bonus-induced MAGI phaseout increases the bonus tax increment');
assert.equal(estimate({year:2025,qualifiedOvertime:1000}).overtimeDeduction,1000);
assert.equal(estimate({year:2026,filingStatus:'mfj',otherIncome:302300,bonusAmount:0,qualifiedOvertime:2000}).overtimeDeduction,1800,'Married joint $300k threshold');

const crossing=estimate({otherIncome:66000,bonusAmount:1000});
assert.equal(crossing.bonusTax,170,'Marginal bracket crossing must calculate progressive rates, not apply 22% to all bonuses');
assert.equal(estimate({otherIncome:0,bonusAmount:325}).bonusTax,0,'Standard deduction shields bonus when other income is zero');
assert.equal(estimate({excludedBonus:'125'}).taxableBonus,200);
assert.equal(estimate({excludedBonus:'325'}).bonusTax,0);
assert.equal(estimate({deduction:'20000'}).usedStandard,false);
assert.equal(estimate({filingStatus:'mfj'}).standardDeduction,32200);
assert.equal(estimate({filingStatus:'hoh'}).standardDeduction,24150);
assert.equal(estimate({filingStatus:'mfs'}).standardDeduction,16100);
assert.equal(calc.estimate({year:2025,filingStatus:'single',otherIncome:'80000',bonusAmount:325}).standardDeduction,15750);
assert.equal(calc.estimate({year:2025,filingStatus:'mfj',otherIncome:'80000',bonusAmount:325}).standardDeduction,31500);
assert.equal(calc.estimate({year:2025,filingStatus:'hoh',otherIncome:'80000',bonusAmount:325}).standardDeduction,23625);
const joint2025=calc.estimate({year:2025,filingStatus:'mfj',otherIncome:128000,bonusAmount:1000});
assert.equal(joint2025.baselineTax,0.10*23850+0.12*(96500-23850),'2025 MFJ baseline rate correctly uses $96,950 boundary');
assert.equal(joint2025.bonusTax,175,'2025 joint tax across $96,950 threshold is $450 at 12% plus $550 at 22%');
assert.equal(calc.estimate({year:2027,filingStatus:'single',otherIncome:1000,bonusAmount:20}).reason,'unsupported-year','Unsupported future brackets may not be estimated');
assert.equal(calc.estimate({year:2026,filingStatus:'',otherIncome:80000,bonusAmount:325}).reason,'filing-status');
assert.equal(calc.estimate({year:2026,filingStatus:'single',otherIncome:'',bonusAmount:325}).reason,'other-income','No auto-inferred salary');
assert.equal(estimate({excludedBonus:400}).reason,'excluded-bonus','Exclusions cannot exceed tracked bonuses');
assert.equal(estimate({withholding:'-2'}).reason,'prepayments');
assert.equal(estimate({otherIncome:'Infinity'}).reason,'other-income');
assert.equal(estimate({bonusAmount:'NaN'}).reason,'bonus-amount');
assert.equal(estimate({otherIncome:'1000000001'}).reason,'other-income');
assert.equal(calc.taxOnOrdinary(50400,[12400,50400,105700,201775,256225,640600]),5800);
assert.equal(calc.taxOnOrdinary(105700,[12400,50400,105700,201775,256225,640600]),17966);
assert.equal(calc.taxOnOrdinary(210000,[24800,100800,211400,403550,512450,768700]),35624);
console.log('Federal tax estimate passed: IRS 2025/2026 schedules, deductions, progressive brackets, withholding, privacy gates, invalid/future inputs');
