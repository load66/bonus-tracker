'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm');
const {sandbox,storage}=require('./full-app-smoke.test.js');
const {fixture}=require('./fixtures/financial-rules.cjs');
const run=s=>vm.runInContext(s,sandbox);
const record={...fixture(),id:'ICLOUD-SYNTH-01',bank:'Synthetic Backup Bank',accountType:'personal',opened:'2026-01-02',bonusRecd:'2026-04-10',closed:'2026-04-12',tcSourceRaw:'Exact synthetic original terms.',feeScheduleRaw:'Exact synthetic fee schedule.',customTimers:[{id:'t1',date:'2026-05-01',done:true}]};
run('entries='+JSON.stringify([record])+';localStorage.setItem(SK,JSON.stringify(entries));');
storage.set('bonus-ai-auth','private-auth-secret-not-for-export');
storage.set('bt_tc_entry_sources_v3',JSON.stringify({'ICLOUD-SYNTH-01':{raw:'Saved enrolled source'}}));
const original=JSON.stringify([...storage]);
const backup=run('buildPortableBackupPayload()');
assert.equal(backup.backupType,'full-fidelity-portable');
assert.equal(backup.entries.length,1);
assert.ok(backup.storageSnapshot.bt_tc_entry_sources_v3,'Saved source must remain in portable backup');
assert.equal(backup.storageSnapshot['bonus-ai-auth'],undefined,'Auth tokens must never enter portable backups');
const receipt=sandbox.BTICloudBackup.verifyPayload(backup);
assert.equal(receipt.accounts,1);
assert.match(receipt.fingerprint,/^[a-f\d]+:\d+$/);
assert.equal(JSON.stringify([...storage]),original,'Read-only file verification cannot change data');
const stale=JSON.parse(JSON.stringify(backup));stale.entries[0].bonus=0;
assert.throws(()=>sandbox.BTICloudBackup.verifyPayload(stale),/Backup validation|file does not include|differ|up-to-date|tracker/i);
run('entries[0].notes="New update after export";localStorage.setItem(SK,JSON.stringify(entries));');
assert.throws(()=>sandbox.BTICloudBackup.verifyPayload(backup),/latest saved|differ/i,'Older files cannot authorize migration');
run('entries[0].notes="";delete entries[0].notes;localStorage.setItem(SK,JSON.stringify(entries));');
// Return to an exact stored fixture for the valid backup.
run('entries='+JSON.stringify([record])+';localStorage.setItem(SK,JSON.stringify(entries));');
const valid=sandbox.BTICloudBackup.verifyPayload(backup);
sandbox.BTPersistence.commit(sandbox.localStorage,{bt_icloud_file_verified_v1:JSON.stringify(valid)});
sandbox.btConfirmDialog=async()=>true;
(async()=>{
 await sandbox.BTICloudBackup.switchToICloud();
 assert.equal(sandbox.localStorage.getItem('bt_backup_mode_v1'),'icloud');
 assert.equal(sandbox.sessionStorage.getItem('bt_icloud_switch_completed_v1'),'1','After reload a one-time successful switch notice must be ready');
 assert.equal(JSON.parse(sandbox.localStorage.getItem('bt_cloud_recovery_v1')).enabled,false);
 assert.deepEqual(JSON.parse(sandbox.localStorage.getItem('bt_e_v4')),[record],'Switch must preserve exact account records');
 assert.equal(sandbox.localStorage.getItem('bonus-ai-auth'),'private-auth-secret-not-for-export','Switch does not delete tokens or unrelated data');
 vm.runInContext(require('node:fs').readFileSync('cloud-backup.js','utf8'),sandbox);
 assert.match(sandbox.BTCloudBackup.protection().title,/Manual iCloud/);
 assert.equal(typeof sandbox.btCloudBeforeDestructive,'function','File restore safety hook must remain callable without Railway');
 await sandbox.btCloudBeforeDestructive('local-file-restore');
 run('entries[0].notes="A new change not in iCloud yet";localStorage.setItem(SK,JSON.stringify(entries));');
 await assert.rejects(sandbox.btCloudBeforeDestructive('pre-reset'),/Safety backup required/,'Unbacked edits must block destructive actions without Railway');
 run('entries='+JSON.stringify([record])+';localStorage.setItem(SK,JSON.stringify(entries));');
 await sandbox.btCloudBeforeDestructive('pre-reset');
 assert.equal(JSON.parse(sandbox.localStorage.getItem('bt_e_v4'))[0].bonus,record.bonus,'Safety guard never writes tracker records');

 vm.runInContext(require('node:fs').readFileSync('cloud-terms-history.js','utf8'),sandbox);
 assert.equal(sandbox.BTTermsHistory.status.pending,0);
 console.log('iCloud migration passed: full source preservation, credential exclusion, stale-file rejection, verified opt-in, no data deletion and server-free verified recovery safeguards');
})().catch(e=>{console.error(e);process.exitCode=1});
