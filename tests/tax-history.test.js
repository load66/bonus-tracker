'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm');
const {sandbox}=require('./full-app-smoke.test.js');
const run=code=>vm.runInContext(code,sandbox);
run(`entries=[{id:'SYN-B-01',bank:'Synthetic Business',accountType:'business',bonus:0,opened:'2026-10-01',closed:'',bonusRecd:'',previousCycles:[{id:'SYN-B-01',bank:'Synthetic Business',accountType:'business',opened:'2026-01-02',closed:'2026-04-20',bonusRecd:'2026-04-12',bonus:250}]}];taxYear=2026;`);
const before=run('JSON.stringify(entries)');
assert.equal(run('normalizeRestoredEntry(entries[0]).previousCycles[0].opened'),'2026-01-02','Restore preserves historical opening dates');
assert.equal(run('taxEntriesForYear(2026).length'),1,'A new cycle must not hide an archived payout from Tax');
assert.equal(run('completedYrTotal(2026)'),250);
assert.equal(run('BT360.heroMonthData(entries,2026)[3].total'),250,'Chart and tax must include the same saved prior cycle');
assert.match(run('rTax()'),/Jan 2, 2026/,'Tax must expose saved opening date');
assert.match(run('rTax()'),/Apr 20, 2026/,'Tax must expose saved closing date');
assert.match(run('rTax()'),/Prior cycle/);
assert.match(run('rTax()'),/View current account/);
assert.match(run('buildTaxCSV(2026)'),/Jan 2, 2026/);
assert.equal(run('JSON.stringify(entries)'),before,'Tax and chart reads must not mutate history');
run(`entries[0].previousCycles.push({...entries[0].previousCycles[0]});`);
assert.equal(run('taxEntriesForYear(2026).length'),1,'Exact duplicate archived receipts must not inflate totals');
run(`entries.push({id:'SYN-P-02',bank:'Synthetic Unknown Dates',accountType:'personal',bonus:75,bonusRecd:'2026-02-04',opened:'',closed:''});`);
assert.match(run('rTax()'),/Opening date not recorded/);
assert.match(run('rTax()'),/No closure recorded/);
assert.equal(run('entries[1].opened'),'','A payout must not invent an opening date');
assert.equal(run('entries[1].closed'),'','No closure date is not proof of a closed account');
run(`entries.push({id:'SYN-P-03',bank:'Other account',accountType:'personal',bonus:75,bonusRecd:'2026-02-04',opened:'',closed:''});`);
assert.equal(run('completedYrTotal(2026)'),400,'Distinct accounts with the same receipt date and amount remain separate');
const prior=run(`(()=>{const row=entries[0];return normalizeNewCycleData({bank:row.bank}, {...row,previousCycles:Array.from({length:15},(_,i)=>({opened:'2020-01-01',bonus:i+1,bonusRecd:'2020-04-01'}))}).previousCycles.length})()`);
assert.equal(prior,15,'New cycle must preserve every already-saved cycle');
run(`startNewCycle('SYN-B-01')`);
assert.equal(run('modal.previousCycles.length'),3,'Starting a cycle must retain archived history without changing live records');
assert.equal(run('entries[0].previousCycles.length'),2);
assert(run('btValidationIssues(entries[1]).some(i=>/Opening date/.test(i.text))'),'Saving a paid account with a missing opening date must show a review warning');
run(`entries[0].previousCycles=Array.from({length:15},(_,i)=>({opened:'2020-01-01',bonus:i+1,bonusRecd:'2020-04-01'}));startNewCycle('SYN-B-01')`);
assert.equal(run('modal.previousCycles.length'),16,'The new-cycle editor must not truncate old history');
const unified=sandbox.BT360.archive(run('entries'));
assert(!unified.includes('bt360-archive-switch'),'Saved terms and cooldown must share one screen');
assert(unified.includes('Churn history & saved terms'),'Unified Archive must retain both purposes');
assert.match(run('rTax()'),/Saved terms for this cycle/,'Tax must link the exact cycle to its enrolled terms');
console.log('Tax history traceability passed: current/prior cycles, dates, totals, distinct accounts, no invented events, read-only projections and history retention');
process.exit(0);
