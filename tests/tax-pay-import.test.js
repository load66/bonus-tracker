'use strict';
const assert=require('node:assert/strict');
require('../tax-pay-import.js');
const p=globalThis.BTTaxPayImport;
assert(p&&p.format==='BonusTrackerTaxPayYTD');
const sample={
 format:'BonusTrackerTaxPayYTD',schemaVersion:1,taxYear:2026,asOfDate:'2026-10-09',
 grossPayYtd:50000,preTaxDeductionsYtd:5000,postTaxDeductionsYtd:750,
 totalEmployeeTaxesYtd:9000,federalTaxableWagesYtd:null,
 federalIncomeTaxWithheldYtd:4000,netPayYtd:38000
};
const now=new Date('2026-10-21T14:00:00');
const copy=p.read(sample,now),projection=p.project(copy);
assert.equal(projection.wageBasis,'gross-less-pretax-proxy');
assert.equal(projection.wageYtd,45000,'Do not mistake gross for federal taxable wages when pre-tax deductions are known');
assert.equal(projection.annualIncome,58244.68);
assert.equal(projection.daysElapsed,282);
assert.equal(projection.daysInYear,365);
assert.equal(projection.federalWithheldYtd,4000);
assert.equal(projection.annualFederalWithholding,5177.3,'Use only explicitly confirmed federal income tax withheld, not total employee taxes');
assert.equal(p.project(p.read({...sample,federalTaxableWagesYtd:44500},now)).wageBasis,'federal-taxable-wages');
assert.equal(p.project(p.read({...sample,federalTaxableWagesYtd:44500},now)).wageYtd,44500);
assert.equal(p.project(p.read({...sample,preTaxDeductionsYtd:null},now)).wageBasis,'gross-pay-proxy');
assert.equal(p.project(p.read({...sample,federalIncomeTaxWithheldYtd:null},now)).annualFederalWithholding,null,'Missing withholding is never inferred from FICA, state or employee tax totals');
assert.equal(p.project(p.read({...sample,taxYear:2025,asOfDate:'2025-12-31'},now)).annualIncome,45000);
assert.throws(()=>p.read({...sample,taxYear:2027,asOfDate:'2027-01-01'},now),/2025 and 2026/);
assert.throws(()=>p.read({...sample,asOfDate:'2026-13-09'},now),/valid/);
assert.throws(()=>p.read({...sample,asOfDate:'2026-10-30'},now),/future pay date/);
assert.throws(()=>p.read({...sample,schemaVersion:99},now),/Unsupported/);
assert.throws(()=>p.read({...sample,format:'OtherProgram'},now),/Unsupported/);
assert.throws(()=>p.read({...sample,unexpected:'hidden user note'},now),/supported/);
assert.throws(()=>p.read({...sample,federalIncomeTaxWithheldYtd:9001},now),/withholding cannot exceed/);
assert.throws(()=>p.read({...sample,federalTaxableWagesYtd:55000},now),/exceed gross/);
assert.throws(()=>p.read({...sample,preTaxDeductionsYtd:-10},now),/nonnegative/);
assert.throws(()=>p.read({...sample,grossPayYtd:NaN},now),/nonnegative/);
assert.throws(()=>p.read({...sample,grossPayYtd:'50000'},now),/nonnegative/);
assert.throws(()=>p.project(p.read({...sample,preTaxDeductionsYtd:60000},now)),/exceed gross/);
const scheduled={...sample,payFrequency:'biweekly',nextPayDate:'2026-10-23'};
const prior={...sample,asOfDate:'2026-09-11',grossPayYtd:46000,preTaxDeductionsYtd:5000,federalIncomeTaxWithheldYtd:3500};
const check=p.project(p.read(scheduled,now),{previous:p.read(prior,now)});
assert.equal(check.remainingPaychecks,5,'Exactly five biweekly paychecks from Oct 23 through Dec 31');
assert.equal(check.trendPaychecks,2,'Count only two actual paydays after earlier snapshot');
assert.equal(check.estimatedWagesPerPaycheck,2000,'Subtract YTD wages, do not sum the two snapshots');
assert.equal(check.estimatedWithheldPerPaycheck,250,'Subtract YTD withholding and divide by two');
assert.equal(check.annualIncome,55000,'Latest YTD wages plus future paychecks only');
assert.equal(check.annualFederalWithholding,5250,'Latest YTD federal withholding plus future paychecks only');
assert.equal(check.projectionMethod,'pay-period-trend');
const stated=p.project(p.read({...scheduled,federalTaxableWagesPerPaycheck:1800,federalIncomeTaxWithheldPerPaycheck:200},now),{previous:p.read(prior,now)});
assert.equal(stated.annualIncome,54000,'User-supplied per-check wages override historical rate');
assert.equal(stated.annualFederalWithholding,5000,'User-supplied per-check withholding overrides historical rate');
assert.equal(stated.projectionMethod,'pay-period-entered');
const initial=p.project(p.read(scheduled,now));
assert.equal(initial.projectionMethod,'calendar-average','Frequency without known per-paycheck amounts does not falsely improve accuracy');
assert.equal(initial.remainingPaychecks,5);
const monthly=p.project(p.read({...sample,payFrequency:'monthly',nextPayDate:'2026-10-31',federalTaxableWagesPerPaycheck:2500},now));
assert.equal(monthly.remainingPaychecks,3,'End-of-month pay schedule must account for November 30 and December 31');
assert.equal(monthly.annualIncome,52500);
const sameDate=p.project(p.read(scheduled,now),{previous:p.read({...prior,asOfDate:'2026-10-09'},now)});
assert.equal(sameDate.projectionMethod,'calendar-average','Same-day corrections are replacements, not new pay periods');
const mixedBasis=p.project(p.read(scheduled,now),{previous:p.read({...prior,federalTaxableWagesYtd:40000},now)});
assert.equal(mixedBasis.projectionMethod,'calendar-average','Never infer trends by comparing incompatible federal wage bases');
assert.throws(()=>p.read({...sample,payFrequency:'daily',nextPayDate:'2026-10-23'},now),/Pay frequency/);
assert.throws(()=>p.read({...sample,payFrequency:'biweekly'},now),/both pay frequency/);
assert.throws(()=>p.read({...sample,nextPayDate:'2026-10-23'},now),/both pay frequency/);
assert.throws(()=>p.read({...sample,payFrequency:'biweekly',nextPayDate:'2026-10-09'},now),/after this YTD/);
assert.throws(()=>p.read({...sample,federalTaxableWagesPerPaycheck:1800},now),/Pay frequency/);
assert.throws(()=>p.read({...sample,payFrequency:'biweekly',nextPayDate:'2026-10-23',federalIncomeTaxWithheldPerPaycheck:-1},now),/nonnegative/);

assert.deepEqual(Object.keys(sample).sort(),Object.keys(sample).sort());
assert.equal(copy.federalTaxableWagesYtd,null,'No estimated W-2 Box 1 value is written into the user-reviewed record');
assert.equal(sample.federalTaxableWagesYtd,null,'Read never mutates the imported JSON');
console.log('Pay JSON import passed: strict schema, verified federal withholding, pre-tax wage proxy, year-end projections, malformed/future year, no inferred W-2 values');
