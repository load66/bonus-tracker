assert.match(s.BT360.sourceEvidencePanel({...dateOnly,analysis:{rawText:'Review <only>'}}),/Read saved review text/);
assert.doesNotMatch(s.BT360.sourceEvidencePanel(dateOnly),/Read original promotion/);
