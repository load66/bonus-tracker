'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm');
const {sandbox:s,storage}=require('./full-app-smoke.test.js');
const run=code=>vm.runInContext(code,s);
const account={id:'SYN-DP',bank:'Synthetic Bonus Bank',accountType:'personal',opened:'2026-09-01',
  bonus:300,dataPoint:'Employer DD',financialRules:{requirements:[{kind:'direct-deposit',amount:500}]}};
run('entries='+JSON.stringify([account])+';sv(SK,entries)');
assert.equal(s.hasDirectDepositRequirement(account),true);
assert.equal(s.hasDirectDepositRequirement({dataPoint:'No DD Required'}),false);
assert.equal(s.normalizeUserDatapoint({bank:'Example',method:'ACH'}).source,'legacy-unverified');
assert.equal(s.normalizeUserDatapoint({bank:'Example',method:'ACH',source:'user-confirmed',
  note:'Auto-saved from bonus received flow'}).source,'tracker-inferred');
s.openReqMet(account.id);
run("reqPrompt.date='2026-09-12';reqSubmit()");
assert.equal(run('cfm.confirmLabel'),'Add datapoint');
assert.equal(s.loadUserDatapoints().length,0,'Milestone never auto-confirms method');
run('cfm.action()');
assert.equal(run('dpEditor.method'),'');
assert.equal(run('dpEditor.outcome'),'unknown');
run("dpEditor.method='Employer payroll';dpEditor.outcome='deposit-posted';saveDPEditor()");
let rows=s.loadUserDatapoints();
assert.equal(rows.length,1);
assert.equal(rows[0].source,'user-confirmed');
assert.equal(rows[0].outcome,'deposit-posted');
assert.equal(rows[0].eventDate,'2026-09-12');
assert.equal(run('entries[0].bonusRecd'),'','Deposit evidence cannot mark bonus paid');
const saved=JSON.stringify(rows[0]);
s.addDD(account.bank,'Employer payroll',300,'2026-10-01',{note:'Auto-saved from successful close'});
assert.equal(JSON.stringify(s.loadUserDatapoints()[0]),saved,'Inferred evidence cannot overwrite confirmation');
s.openRcv(account.id);
run("rcvPrompt.date='2026-09-20';rcvPrompt.reqDate='2026-09-12';rcvSubmit()");
assert.equal(run('entries[0].bonusRecd'),'2026-09-20');
assert.equal(run('cfm.confirmLabel'),'Add datapoint');
assert.equal(s.loadUserDatapoints().length,1,'Payout save must not silently create method success');
run('cfm.action()');
assert.equal(run('dpEditor.outcome'),'unknown');
run("dpEditor.method='ACH push';dpEditor.outcome='bonus-received';saveDPEditor()");
rows=s.loadUserDatapoints();
assert.equal(rows.length,2);
assert.equal(rows[0].outcome,'bonus-received');
const unchanged=JSON.stringify([...storage]);
assert(s.rTips().includes('Confirmed by you'));
assert.equal(JSON.stringify([...storage]),unchanged,'Reports read cannot mutate data');
console.log('Datapoint opt-in, source and evidence tests passed');
