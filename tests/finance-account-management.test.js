'use strict';
const assert=require('node:assert/strict');
const U=require('../finance-unified-core'),F=require('../finance-overview-core');
const now=1792134000,A='a'.repeat(64),B='b'.repeat(64),a='simplefin:'+A,b='plaid:'+B;
const row=(id,amount='-10.00')=>({id,amount,posted:now-60,pending:false,description:'Synthetic Cafe',category:'dining',categorySource:'user'});
const source=(key,bank,name,mask)=>({connected:true,lastSuccess:now,accounts:[{key,bank,name,mask,currency:'USD',balance:'100.00',balanceDate:now,accountType:'checking'}],monitoredAccounts:[key],transactions:{[key]:{one:row('one'),two:row('two')}},accountProfiles:{[key]:{kind:'checking',balanceMode:'asset',includeSpending:true}}});
const simple=source(A,'Chase Bank','Total Checking','4010'),plaid=source(B,'JPMorgan Chase','Everyday','4010');
const combined=U.combine({simplefin:simple,plaid});
assert.equal(combined.possibleDuplicates.length,1,'mask, type and similar institution find mismatched account names');
assert.equal(U.safeForSummary(combined).accounts.length,0,'unconfirmed matches remain excluded and partial');
const confirmed=U.combine({simplefin:simple,plaid},{duplicates:{[a+'|'+b]:{primary:a}}});
const before=JSON.stringify(confirmed);
let safe=U.safeForSummary(confirmed);
assert.equal(safe.accounts.length,1);assert.equal(Object.keys(safe.transactions[a]).length,2,'same-provider duplicate purchases are both retained');
assert.equal(F.summarize(safe,{now}).expenses,'20.00');
U.safeForSummary(confirmed);assert.equal(JSON.stringify(confirmed),before,'summaries never mutate the source snapshots');
plaid.transactions[B].three=row('three','-25.00');
safe=U.safeForSummary(U.combine({simplefin:simple,plaid},{duplicates:{[a+'|'+b]:{primary:a}}}));
assert.equal(Object.keys(safe.transactions[a]).length,3,'unique secondary history remains available');
assert.equal(F.summarize(safe,{now}).expenses,'45.00');
const off=structuredClone(simple);off.accountProfiles[A].includeSpending=false;
assert.equal(F.summarize(U.safeForSummary(U.combine({simplefin:off})),{now}).expenses,null);
assert.equal(F.summarize(U.safeForSummary(U.combine({simplefin:off})),{now}).netWorth,'100.00','spending switch does not change net worth');
off.accountProfiles[A].balanceMode='exclude';
assert.equal(F.summarize(U.safeForSummary(U.combine({simplefin:off})),{now}).netWorthAvailable,false);
const removed=structuredClone(simple);removed.accounts[0].removedAt=now;
let summary=F.summarize(U.safeForSummary(U.combine({simplefin:removed})),{now});
assert.equal(summary.expenses,'20.00','removal keeps past spending');assert.equal(summary.cashAvailable,false,'removed balances do not enter cash');
removed.accountProfiles[A].hidden=true;
assert.equal(F.summarize(U.safeForSummary(U.combine({simplefin:removed})),{now}).expenses,null,'hide removes activity from Finance totals without deleting it');
assert.equal(Object.keys(removed.transactions[A]).length,2);
const fs=require('node:fs');const page=fs.readFileSync(require('node:path').join(__dirname,'../finance-page.js'),'utf8');
for(const phrase of ['Not assigned — review manually','Import official T&C','verified terms'])assert.ok(!page.includes(phrase));
console.log('Finance account management: duplicate confirmation, nonmutation, removal history, include switches, hidden accounts and copy passed');
