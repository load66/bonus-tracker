'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const {sandbox:s,storage}=require('./full-app-smoke.test.js');
const run=code=>vm.runInContext(code,s);
const saved=JSON.stringify([...storage]);

(async()=>{
  s.openAdd();
  assert.equal(s.btEditorHasChanges(),false,'Fresh draft is not dirty');
  assert.match(s.rModal(),/aria-label="Close account editor"/,'Editor has an explicit close button');
  assert.match(s.rModal(),/aria-current="step"/,'Step navigation exposes current step');
  assert.match(s.rModal(),/aria-label="Step 2: Requirements"/,'Step labels stay accessible');
  s.btWizardStep(2);
  assert.equal(run('modal._wizardStep'),2,'Step 2 is selected');
  assert.equal(s.btEditorHasChanges(),false,'Navigation alone cannot trigger discard warning');
  s.btWizardStep(4);
  assert.match(s.rModal(),/class="bt3656-fix"/,'Review validation gives a direct correction link');
  assert.equal(JSON.stringify([...storage]),saved,'Step changes cannot write records');
  s.btWizardStep(1);
  s.btModalSet('bank','Synthetic Draft Example');
  assert.equal(s.btEditorHasChanges(),true,'Editing a field is treated as unsaved');
  let prompts=0;
  s.btConfirmDialog=async()=>{prompts++;return false};
  assert.equal(s.btEditorRequestClose(),false,'Closing changed draft requires confirmation');
  await new Promise(resolve=>setTimeout(resolve,10));
  assert.equal(prompts,1);
  assert.equal(run('modal.bank'),'Synthetic Draft Example','Keep editing preserves draft');
  assert.equal(run('!!modal'),true,'Declining exit leaves editor open');
  s.btConfirmDialog=async()=>true;
  s.btEditorRequestClose();
  await new Promise(resolve=>setTimeout(resolve,10));
  assert.equal(run('modal'),null,'Confirmed exit closes draft');
  assert.equal(JSON.stringify([...storage]),saved,'Discarding draft leaves stored records unchanged');
  s.openAdd();
  assert.equal(s.btEditorHasChanges(),false,'New editor starts with clean draft');
  s.btEditorRequestClose();
  assert.equal(run('modal'),null,'Unchanged editor closes with no prompt');
  assert.equal(JSON.stringify([...storage]),saved,'No edit path can alter persisted records');
  console.log('Mobile guided editor: visible steps, safe navigation, unchanged close, confirm discard, no writes PASS');
})().catch(error=>{console.error(error);process.exitCode=1});
