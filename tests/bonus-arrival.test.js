'use strict';
const assert=require('node:assert/strict');
const rules=require('../financial-rules.js');
const {fixture}=require('./fixtures/financial-rules.cjs');
const make=(text,window)=>{
 const e=fixture();e.financialRules.version=3;e.tcSourceRaw+=' '+text;e.payoutTimingText=text;
 e.financialRules.payout={text,evidence:{source:'promotion',quote:text},...(window?{window}:{})};return e;
};
const text='Bonus is paid between the 90th and 120th calendar day after account opening, provided the account stays open and in good standing.';
const w={basis:'opened',unit:'calendar-days',min:90,max:120};
const c=make(text,w);c.opened='2026-08-10';
assert.equal(rules.validate(c).ok,true);
assert.deepEqual(rules.estimatedArrival(c),{start:'2026-11-08',end:'2026-12-08',basis:'opened',anchor:'2026-08-10'});
assert.equal(rules.arrivalLabel(rules.estimatedArrival(c)),'Estimated bonus arrival: Nov 8–Dec 8, 2026');
const initial=JSON.stringify(c);
for(const reqMet of ['','2026-09-24','2026-10-26'])assert.equal(rules.estimatedArrival({...c,reqMet}).start,'2026-11-08','Opening-based payout never moves to requirement completion');
assert.equal(JSON.stringify(c),initial,'Calculation never rewrites financial records');
const f=make('Bonus is paid within 60 calendar days after all requirements are met.',{basis:'reqmet',unit:'calendar-days',min:0,max:60});
assert.equal(rules.estimatedArrival(f),null,'Terms do not confirm activity');
f.reqMet='2026-09-24';
assert.equal(rules.estimatedArrival(f).end,'2026-11-23');
assert.equal(rules.estimatedArrival(f).start,'2026-09-24','Within gives the full possible range, never a made-up narrower lower bound');
assert.equal(rules.estimatedArrival({...f,reqMet:'2026-10-26'}).end,'2026-12-25','Changing completion recomputes both bounds');
assert.equal(rules.estimatedArrival({...f,reqMet:''}),null,'Clearing completion clears projection');
for(const e of [{...f,bonusRecd:'2026-10-28'},{...f,closed:'2026-10-28'},{...f,reqMet:'2026-02-30'}])assert.equal(rules.estimatedArrival(e),null);
const changed=JSON.parse(JSON.stringify(c));changed.financialRules.payout.window.min=100;
assert.equal(rules.validate(changed).ok,false,'Unquoted lower bound rejected');
assert.equal(rules.estimatedArrival(changed),null,'Invalid structured rules never fall back to legacy wording');
for(const version of [1,2]){const e=fixture();e.financialRules.version=version;e.reqMet='2026-09-24';assert.equal(rules.estimatedArrival(e).end,'2026-11-23','Existing supported rules remain read-only compatible');}
const legacy={opened:'2026-08-10',payoutTimingText:text};
assert.equal(rules.estimatedArrival(legacy).end,'2026-12-08');
assert.equal(rules.estimatedArrival({opened:'2026-01-01',payoutTimingText:'Payout after bank review.'}),null);
const month=make('Bonus is paid within 1 calendar month after account opening.');month.opened='2026-01-31';
assert.equal(rules.estimatedArrival(month).end,'2026-02-28');month.opened='2028-01-31';assert.equal(rules.estimatedArrival(month).end,'2028-02-29');
for(const unit of ['business days','statement cycles'])assert.equal(rules.estimatedArrival(make('Bonus is paid within 2 '+unit+' after account opening.')),null,'No fixed-day approximations');
assert.equal(rules.estimatedArrival({opened:'2026-01-31',payoutTimingText:'Within 60 days after requirements are met or after account opening.'}),null,'Ambiguous anchors cannot produce a range');
assert.equal(rules.estimatedArrival({opened:'2026-02-30',payoutTimingText:text}),null);
const enrollment=make('Bonus is paid within 30 calendar days after offer enrollment.');enrollment.offerEnrollmentDate='2026-12-15';
assert.equal(rules.estimatedArrival(enrollment).end,'2027-01-14');
assert.match(rules.arrivalLabel(rules.estimatedArrival(enrollment)),/Dec 15, 2026–Jan 14, 2027/);
const period=make('Bonus is paid within 30 calendar days after the qualifying period ends.');
assert.equal(rules.estimatedArrival(period),null,'Qualification-end cannot be assumed to be opening or completion');
period.tcSourceRaw+=' Complete 90 calendar days after account opening.';
period.financialRules.requirements[0].timing={basis:'opened',unit:'calendar-days',value:90};
period.financialRules.requirements[0].evidence.quote+=' Complete 90 calendar days after account opening.';
// Keep the original requirement quotation contiguous for evidence validation.
period.tcSourceRaw=period.tcSourceRaw.replace('months. Bonus','months. Complete 90 calendar days after account opening. Bonus');
assert.equal(rules.estimatedArrival(period)?.end,'2026-05-31');
console.log('Bonus arrival: source-backed bounds, exact anchors, recalculation, missing data, calendar boundaries, ambiguous rules and no mutation passed');
const {sandbox,storage}=require('./full-app-smoke.test.js');
const before=JSON.stringify([...storage]);
const envelope={kind:'BonusTrackerEntry',schemaVersion:3,verification:{promoSourceUrl:c.promoSourceUrl,feeScheduleSourceUrl:c.feeScheduleSourceUrl,termsVerifiedAt:c.termsVerifiedAt},entry:c};
sandbox.btStageEntryPayload(envelope);
const projected=sandbox.collectModalEntryData();
assert.equal(JSON.stringify(projected.financialRules),JSON.stringify(c.financialRules));
assert.equal(sandbox.BTFinancialRules.estimatedArrival(projected).end,'2026-12-08');
assert(sandbox.BTBonusAI.contextFor(projected).some(x=>x.id==='arrival'&&/Nov 8–Dec 8/.test(x.text)));
assert.match(sandbox.BT360.detailPanels(projected),/Estimated bonus arrival: Nov 8–Dec 8, 2026/);
assert.equal((sandbox.BT360.detailPanels(projected).match(/Estimated bonus arrival/g)||[]).length,1,'One arrival line per detail');
assert.doesNotMatch(sandbox.BT360.detailPanels(projected),/confidence|bt3684[^>]*badge/i);
assert.equal(JSON.stringify([...storage]),before,'Import review and date display do not write live records');
const vm=require('node:vm');sandbox.__arrivalTest=projected;
const backup=vm.runInContext('JSON.stringify(buildPortableBackupPayload())',sandbox);
assert(backup,'Backup remains available');
// Save and backup only this isolated synthetic harness, never provider data.
vm.runInContext('entries=[{...__arrivalTest,id:"SYN-ARRIVAL"}];sv(SK,entries)',sandbox);
const saved=JSON.parse(storage.get('bt_e_v4'))[0];
assert.equal(JSON.stringify(saved.financialRules.payout.window),JSON.stringify(w));
const portable=vm.runInContext('JSON.stringify(buildPortableBackupPayload())',sandbox);
assert(portable.includes('"min":90')&&portable.includes('"max":120'),'Backup preserves typed bounds');
assert.equal(sandbox.BTFinancialRules.estimatedArrival(saved).end,'2026-12-08');
console.log('Arrival JSON import/review/save/backup, AI context and single-line display passed');
